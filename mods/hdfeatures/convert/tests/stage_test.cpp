Bytes unhex(std::string_view h) {
    Bytes out(h.size() / 2);
    auto nib = [](char c) { return c <= '9' ? c - '0' : c - 'a' + 10; };
    for (std::size_t i = 0; i < out.size(); ++i) out[i] = static_cast<u8>((nib(h[2 * i]) << 4) | nib(h[2 * i + 1]));
    return out;
}

std::string join(const std::vector<std::string>& v) {
    std::string s;
    for (std::size_t i = 0; i < v.size(); ++i) {
        if (i) s += '\n';
        s += v[i];
    }
    return s;
}

std::string sha(View d) { return hdf::sha256_hex(d); }
std::string sha(const std::string& s) { return hdf::sha256_hex(View(reinterpret_cast<const u8*>(s.data()), s.size())); }
std::string r(float f) { return io::py_float_repr(static_cast<double>(f)); }

