    const Bytes room = unhex(kRoomHex);
    auto cs = stage::chunks(room);
    HDF_CHECK(cs.has_value());
    if (!cs) return;
    HDF_CHECK_EQ(cs->size(), std::size_t(8));
    HDF_CHECK_EQ((*cs)[1].tag, std::string("ACTR"));
    HDF_CHECK_EQ((*cs)[1].header_offset, u32(16));
    HDF_CHECK_EQ((*cs)[7].count, u32(0xFFFFFFFF));  // a negative count: kept raw, loops run 0 times
    HDF_CHECK(stage::find_chunk(*cs, "SCOB") == &(*cs)[3]);
    HDF_CHECK(stage::find_chunk(*cs, "NONE") == nullptr);
    auto recs = stage::records(room);
    HDF_CHECK(recs.has_value());
    if (!recs) return;
    HDF_CHECK_EQ(recs->size(), kRoomRecordsCount);
    // the line format of tools/dev/golden_stage.py record_lines (floats as repr())
    std::string lines;
