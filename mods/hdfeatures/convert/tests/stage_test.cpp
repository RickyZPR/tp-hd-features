HDF_TEST(stage_corrupt_inputs_never_crash) {
    // Random byte changes and truncations of every synthetic input: each call gives a value or an error.
    std::mt19937 rng(12345);
    const Bytes room = unhex(kRoomHex), stg = unhex(kStageHex), losb = unhex(kLosHex);
    const auto st = stats();
    auto mutate = [&](Bytes b) {
        const int n = 1 + static_cast<int>(rng() % 8);
        for (int i = 0; i < n && !b.empty(); ++i) {
            const std::size_t at = rng() % b.size();
            switch (rng() % 4) {
                case 0: b[at] = static_cast<u8>(rng()); break;
                case 1: b[at] ^= 0x80; break;
                case 2: b[at] = 0xFF; break;
                default: b.resize(at); break;
            }
        }
        return b;
    };
    int values = 0, errors = 0;
    auto tally = [&](bool ok) {
        if (ok) {
            ++values;
        } else {
            ++errors;
        }
    };
    for (int it = 0; it < 3000; ++it) {
        const Bytes r1 = mutate(room), s1 = mutate(stg), l1 = mutate(losb);
        tally(stage::chunks(r1).has_value());
        tally(stage::records(r1).has_value());
        tally(stage::stag(s1).has_value());
        tally(stage::patch_room(25, r1, prod()).has_value());
        tally(stage::patch_room(49, r1, variant("reward")).has_value());
        tally(stage::add_scls(r1, View(r1).first(std::min<std::size_t>(r1.size(), 13))).has_value());
        tally(stage::stage_mem_tables(s1).has_value());
        auto lt = stage::read_los(l1);
        tally(lt.has_value());
        const stage::LosTable L = lt ? *lt : los();
        if (lt) tally(stage::floor_chain(*lt).has_value());
        tally(stage::patch_stage(s1, st, L, prod()).has_value());
        tally(stage::patch_stage_mem(s1, L, prod(), std::vector<u32>{1, 2, 3}).has_value());
        if (it % 10 == 0) {
            hdf::MemorySource hd("fuzz");
            const std::vector<std::pair<std::string, Bytes>> f1{{"dzr/room.dzr", mutate(unhex(kTagRoomHex[0]))}};
            const std::vector<std::pair<std::string, Bytes>> f2{{"dzr/room.dzr", mutate(unhex(kTagRoomHex[1]))}};
            hd.add("res/Stage/D_SB11/R10_00.arc", mutate(io::rarc_build("r10_00", f1)));
            hd.add("res/Stage/D_SB11/R48_00.arc", io::rarc_build("r48_00", f2));
            for (std::size_t i = 0; i < hdf::facts::kHdChests.size(); ++i) {
                const hdf::facts::HdChest& c = hdf::facts::kHdChests[i];
                char path[64];
                std::snprintf(path, sizeof path, "res/Stage/%.*s/R%02u_00.arc", int(c.stage.size()), c.stage.data(),
                              unsigned(c.room));
                const std::vector<std::pair<std::string, Bytes>> f{{"dzr/room.dzr", mutate(unhex(kChestDzrHex[i]))}};
                hd.add(path, io::rarc_build("r00_00", f));
            }
            tally(stage::hd_tags_bin(hd).has_value());
            tally(stage::hd_chests_bin(hd).has_value());
        }
    }
    HDF_CHECK(values > 0 && errors > 0);
}
