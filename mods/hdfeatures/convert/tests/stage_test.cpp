HDF_TEST(stage_add_scls_and_drop_records) {
    const Bytes room = unhex(kRoomHex);
    const u8 rec[15] = {'A', 'B', 'C', 'D', 'E', 'F', 'G', 'H', 1, 2, 3, 4, 5, 6, 7};
    auto added = stage::add_scls(room, View(rec, 15));
    HDF_CHECK(added.has_value());
    if (added) {
        HDF_CHECK(added->second);
        HDF_CHECK_EQ(added->first.size(), kAddSclsSize);
        HDF_CHECK_EQ(sha(added->first), std::string(kAddSclsSha));
        auto again = stage::add_scls(added->first, View(rec, 15));  // already has an SCLS: unchanged
        HDF_CHECK(again.has_value() && !again->second && again->first == added->first);
    }
    // drop every door: the Doo2 chunk keeps its place, its count drops to 0 and the record is zero-filled
    std::vector<std::string> rep;
    auto dropped = stage::drop_records(7, room,
                                       [](std::string_view, std::string_view name, u32, const std::array<hdf::i16, 3>&) {
                                           return name == "door";
                                       },
                                       &rep);
    HDF_CHECK(dropped.has_value());
    if (dropped) {
        HDF_CHECK_EQ(dropped->size(), room.size());
        auto cs = stage::chunks(*dropped);
        HDF_CHECK(cs.has_value() && (*cs)[5].tag == "Doo2" && (*cs)[5].count == 0);
        if (cs) {
            bool zero = true;
            for (u32 i = 0; i < 0x24; ++i) zero = zero && (*dropped)[(*cs)[5].offset + i] == 0;
            HDF_CHECK(zero);
        }
        HDF_CHECK_EQ(join(rep), std::string("R07 Doo2 door prm 00000044 ang (0, 0, 0) deleted"));
    }
}

