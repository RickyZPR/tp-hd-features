HDF_TEST(stage_patch_stage_errors) {
    const Bytes stg = unhex(kStageHex);
    const stage::LosTable L = los();
    // MEM0 has 3 blocks: 2 sizes are refused (ValueError)
    HDF_CHECK(!stage::patch_stage_mem(stg, L, prod(), std::vector<u32>{1, 2}).has_value());
    // room 1 wants 2 RTBL entries; make its list 1 byte long (room 2's list starts one byte later): ValueError
    auto cs = stage::chunks(stg);
    HDF_CHECK(cs.has_value());
    if (!cs) return;
    const stage::Chunk* rt = stage::find_chunk(*cs, "RTBL");
    HDF_CHECK(rt != nullptr);
    if (!rt) return;
    Bytes bad = stg;
    const u32 e1 = io::be32(bad, rt->offset + 4), e2 = io::be32(bad, rt->offset + 8);
    io::put32(bad, e2 + 4, io::be32(bad, e1 + 4) + 1);
    auto x = stage::patch_stage_mem(bad, L, prod(), std::nullopt);
    HDF_CHECK(!x.has_value() && x.error().code == "fmt.stage");
    // no RTBL chunk (KeyError): rename the tag
    Bytes no_rtbl = stg;
    no_rtbl[rt->header_offset] = 'X';
    HDF_CHECK(!stage::patch_stage_mem(no_rtbl, L, prod(), std::nullopt).has_value());
    auto o = prod();
    o.no_rtbl = true;
    HDF_CHECK(stage::patch_stage_mem(no_rtbl, L, o, std::nullopt).has_value());
}

