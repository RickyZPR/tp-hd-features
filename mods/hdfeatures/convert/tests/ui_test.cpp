std::optional<std::string> sjis_hex(std::string_view hex) {
    Bytes b;
    for (std::size_t i = 0; i + 1 < hex.size(); i += 2)
        b.push_back(static_cast<u8>(std::stoi(std::string(hex.substr(i, 2)), nullptr, 16)));
    auto r = dt::shift_jis_to_utf8(b);
    if (!r) return std::nullopt;
    return hex_utf8(*r);
}

