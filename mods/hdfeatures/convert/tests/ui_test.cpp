// Every Shift-JIS pair against Python's codec (hash of the whole table). Without Windows (cp932 through
// MultiByteToWideChar) only ASCII and half-width katakana decode, so the table check is Windows only.
HDF_TEST(ui_shift_jis_table) {
#ifdef _WIN32
    std::string lines;
    int ok = 0;
    char buf[16];
    for (u32 lead = 0x81; lead <= 0xFF; ++lead)
        for (u32 trail = 0x40; trail <= 0xFF; ++trail) {
            const u8 pair[2] = {static_cast<u8>(lead), static_cast<u8>(trail)};
            u32 cp = 0;
            if (auto s = dt::shift_jis_to_utf8(View(pair, 2))) {
                // one character: decode the UTF-8 back to a code point
                const auto* p = reinterpret_cast<const unsigned char*>(s->data());
                if (s->size() == 1)
                    cp = p[0];
                else if (s->size() == 2 && (p[0] & 0xE0) == 0xC0)
                    cp = ((p[0] & 0x1Fu) << 6) | (p[1] & 0x3Fu);
                else if (s->size() == 3 && (p[0] & 0xF0) == 0xE0)
                    cp = ((p[0] & 0x0Fu) << 12) | ((p[1] & 0x3Fu) << 6) | (p[2] & 0x3Fu);
            }
            ok += cp != 0;
            std::snprintf(buf, sizeof buf, "%02x%02x=%04x\n", lead, trail, cp);
            lines += buf;
        }
    HDF_CHECK_EQ(ok, kSjisPairsOk);
    HDF_CHECK_EQ(hdf::sha256_hex(View(reinterpret_cast<const u8*>(lines.data()), lines.size())),
                 std::string(kSjisPairsSha256));
#else
    HDF_SKIP("cp932 table needs Windows");
#endif
}

