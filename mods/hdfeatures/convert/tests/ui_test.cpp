// stampbook.Blo (+ cosconfirm's aid) on the same BLO: TEX1 references, blocks, counts, walk order, _place.
HDF_TEST(ui_blo_read_vector) {
    auto b = dt::blo_read(blo_view());
    HDF_CHECK(b.has_value());
    if (!b) return;
    HDF_CHECK_EQ(b->tex.size(), kBloTex.size());
    for (std::size_t i = 0; i < b->tex.size() && i < kBloTex.size(); ++i) {
        HDF_CHECK_EQ(int(b->tex[i].kind), kBloTex[i].first);
        HDF_CHECK_EQ(b->tex[i].raw, kBloTex[i].second);
        HDF_CHECK_EQ(b->tex[i].name, kBloTex[i].second);  // ASCII: latin-1 = bytes
    }
    HDF_CHECK(b->blocks == kBloBlocks);
    HDF_CHECK_EQ(b->counts.size(), kBloCounts.size());
    for (std::size_t i = 0; i < b->counts.size() && i < kBloCounts.size(); ++i) {
        HDF_CHECK_EQ(b->counts[i].first, kBloCounts[i].first);
        HDF_CHECK_EQ(int(b->counts[i].second), kBloCounts[i].second);
    }
    std::vector<const dt::BloPane*> walk;
    std::vector<const dt::BloPane*> todo{b->root.get()};
    while (!todo.empty()) {  // pre-order, children in order (Blo.walk)
        const dt::BloPane* p = todo.back();
        todo.pop_back();
        walk.push_back(p);
        for (auto it = p->children.rbegin(); it != p->children.rend(); ++it) todo.push_back(it->get());
    }
    HDF_CHECK_EQ(walk.size(), kBloWalk.size());
    for (std::size_t i = 0; i < walk.size() && i < kBloWalk.size(); ++i) {
        HDF_CHECK_EQ(walk[i]->name, kBloWalk[i]);
        // _place feeds only the dropped manifests and previews: cos/sin may differ in the last bit between CRTs,
        // so this compares to 1e-12.
        const auto& m = walk[i]->m;
        const double got[6] = {m[0][0], m[0][1], m[0][2], m[1][0], m[1][1], m[1][2]};
        for (int k = 0; k < 6; ++k) HDF_CHECK(std::fabs(got[k] - kBloPlace[i][k]) < 1e-12);
    }
    if (walk.size() == 7) {
        HDF_CHECK_EQ(walk[2]->aid, u16{3});  // pic_a: J2DPane animation index
        HDF_CHECK_EQ(walk[1]->aid, u16{0xFFFF});
        HDF_CHECK(walk[2]->material.has_value() && *walk[2]->material == 0);
        HDF_CHECK(walk[5]->material.has_value() && *walk[5]->material == 1);  // WIN2 +0x24
        HDF_CHECK(!walk[3]->visible);
    }
    HDF_CHECK_EQ(b->mats.size(), std::size_t{2});
    if (b->mats.size() == 2) {
        HDF_CHECK_EQ(b->mats[0].textures.size(), std::size_t{2});
        HDF_CHECK_EQ(b->mats[0].tevstages, 3u);
        HDF_CHECK(b->mats[0].matcolor.has_value());
        HDF_CHECK(b->mats[0].tevcolor[0].has_value() && (*b->mats[0].tevcolor[0])[1] == 256);
        HDF_CHECK(!b->mats[0].tevcolor[2].has_value());
        HDF_CHECK_EQ(b->mats[1].tevstages, 1u);
    }
}

// Every prefix of the BLO and random byte flips: an error or a value, never a crash or a hang.
HDF_TEST(ui_blo_truncated_and_random) {
    const View v = blo_view();
    for (std::size_t n = 0; n <= v.size(); ++n) {
        (void)dt::parse_blo(v.subspan(0, n));
        (void)dt::blo_read(v.subspan(0, n));
    }
    const Bytes b(v.begin(), v.end());
    for (int round = 0; round < 3000; ++round) {
        Bytes c = b;
        const int flips = 1 + static_cast<int>(lcg() % 6);
        for (int k = 0; k < flips; ++k) c[lcg() % c.size()] = static_cast<u8>(lcg());
        (void)dt::parse_blo(c);
        (void)dt::blo_read(c);
        (void)dt::res_ref(c, 0x20 + (lcg() % 64));
        (void)dt::name_tab(c, lcg() % c.size());
        (void)dt::blo_resrefs(c, lcg() % c.size());
    }
    // a block of size 0 (Python loops forever on it) is refused by both readers
    Bytes z(v.begin(), v.begin() + 0x20);
    const u8 inf[8] = {'I', 'N', 'F', '1', 0, 0, 0, 0};
    z.insert(z.end(), inf, inf + 8);
    z.resize(z.size() + 8, 0);
    HDF_CHECK(!dt::parse_blo(z).has_value());
    HDF_CHECK(!dt::blo_read(z).has_value());
    HDF_CHECK(!dt::parse_blo(View()).has_value());  // not a SCRN blo
}

