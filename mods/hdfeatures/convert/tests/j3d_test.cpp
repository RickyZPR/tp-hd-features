HDF_TEST(j3d_convert_model_vectors) {
    for (const auto& v : kModelVecs) {
        const Bytes m = unhex(v.model);
        Bytes g;
        std::optional<View> gtx;
        if (v.gtx) {
            g = unhex(v.gtx);
            gtx = View(g);
        }
        std::vector<std::string> rep;
        auto c = j3d::convert_j3d(m, gtx, &rep);
        HDF_CHECK(c.has_value());
        if (!c) continue;
        HDF_CHECK_EQ(sha(*c), std::string(v.conv));
        HDF_CHECK_EQ(static_cast<int>(rep.size()), v.nreport);
        HDF_CHECK_EQ(sha(join(rep)), std::string(v.report));
        // matstride.effective_stride of every MAT block of the convert_j3d output
        std::string strides;
        auto secs = j3d::sections(*c);
        HDF_CHECK(secs.has_value());
        if (secs)
            for (const j3d::Section& s : *secs)
                if (std::memcmp(s.tag.data(), "MAT3", 4) == 0 || std::memcmp(s.tag.data(), "MAT4", 4) == 0) {
                    auto es = j3d::mat_effective_stride(*c, s.offset);
                    char b[16];
                    std::snprintf(b, sizeof b, "%x", es && *es ? **es : 0u);
                    strides += std::string(strides.empty() ? "" : ",") + (!es ? "err" : !*es ? "-" : b);
                }
        HDF_CHECK_EQ(strides, std::string(v.strides));
        auto f = j3d::mat4fix(*c);
        HDF_CHECK(f.has_value());
        if (!f) continue;
        HDF_CHECK_EQ(f->fixed, v.fixed);
        HDF_CHECK_EQ(sha(f->data), std::string(v.fixd));
        auto dl = j3d::pc_dl_detail(f->data);
        const std::string dls = dl ? std::to_string(dl->shapes) + " " + std::to_string(dl->packets) + " " +
                                         std::to_string(dl->raw) + " " + std::to_string(dl->optimized) + " " +
                                         std::to_string(dl->copy)
                                   : "err";
        HDF_CHECK_EQ(dls, std::string(v.dl));
        auto bytes = j3d::pc_dl_bytes(f->data);
        HDF_CHECK(bytes.has_value() == dl.has_value());
        if (bytes && dl) HDF_CHECK_EQ(*bytes, dl->copy);
        const hdf::ModelStats ms = j3d::model_stats(f->data);
        HDF_CHECK_EQ(std::to_string(ms.mat) + " " + std::to_string(ms.shp) + " " + std::to_string(ms.jnt) + " " +
                         std::to_string(ms.tex) + " " + std::to_string(ms.dl),
                     std::string(v.mstats));
        auto again = j3d::mat4fix(f->data);  // idempotent
        HDF_CHECK(again.has_value());
        if (again) {
            HDF_CHECK_EQ(again->fixed, v.idem_fixed);
            HDF_CHECK_EQ(again->data == f->data ? 1 : 0, v.idem_same);
        }
    }
}

HDF_TEST(j3d_bake_vectors) {
    const auto fixed = fixed_models();
    int ok = 0, err = 0;
    for (const auto& v : kBakeVecs) {
        auto it = fixed.find(v.model);
        HDF_CHECK(it != fixed.end());
        if (it == fixed.end()) continue;
        auto b = j3d::bake_los(it->second, {v.t[0], v.t[1], v.t[2]}, v.angle);
        std::string got = "err";
        if (b) {
            got = sha(b->data) + " " + std::to_string(b->vertices);
            for (double x : b->min) got += " " + io::py_float_repr(x);
            for (double x : b->max) got += " " + io::py_float_repr(x);
        } else {
            HDF_CHECK_EQ(b.error().code, std::string("fmt.j3d"));
        }
        HDF_CHECK_EQ(got, std::string(v.result));
        (b ? ok : err) += 1;
    }
    HDF_CHECK(ok >= 25 && err >= 30);  // both paths run (successful bakes at every angle; refusals)
    // only the 4 los angles have a table entry
    auto it = fixed.find("f");
    HDF_CHECK(it != fixed.end());
    if (it != fixed.end())
        for (const int ang : {0x2000, -1, 0x8000, 12345}) {
            auto b = j3d::bake_los(it->second, {0.f, 0.f, 0.f}, ang);
            HDF_CHECK(!b.has_value() && b.error().code == "fmt.j3d");
        }
}

HDF_TEST(j3d_bake_signed_zero_matters) {
    // Model F's -0x8000 bake must differ from the 0x0 and 0x4000 ones and equal the spec (kBakeVecs); the spec's
    // own sensitivity to the sign of sin(-pi) rounded to 9 digits was checked when the vectors were made (a
    // +0.0 table gives other hashes for all 4 model-F bakes at -0x8000).
    std::string first;
    for (const auto& v : kBakeVecs)
        if (std::string(v.model) == "f" && v.angle == -0x8000) {
            first = v.result;
            break;
        }
    HDF_CHECK(first != "err" && !first.empty());
    for (const auto& a : kAngleBits) {
        double c, s;
        std::memcpy(&c, &a.c, 8);
        std::memcpy(&s, &a.s, 8);
        if (a.angle == -0x8000) {
            HDF_CHECK(c == -1.0 && s == 0.0 && std::signbit(s));
        }
    }
}

