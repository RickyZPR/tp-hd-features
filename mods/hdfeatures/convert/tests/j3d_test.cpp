Bytes unhex(std::string_view h) {
    auto nib = [](char c) -> u8 {
        if (c >= '0' && c <= '9') return static_cast<u8>(c - '0');
        if (c >= 'a' && c <= 'f') return static_cast<u8>(c - 'a' + 10);
        return static_cast<u8>(c - 'A' + 10);
    };
    Bytes b(h.size() / 2);
    for (std::size_t i = 0; i < b.size(); ++i) b[i] = static_cast<u8>(nib(h[2 * i]) << 4 | nib(h[2 * i + 1]));
    return b;
}

std::string sha(View d) { return hdf::sha256_hex(d); }
std::string sha(const std::string& s) { return hdf::sha256_hex(View(reinterpret_cast<const u8*>(s.data()), s.size())); }

std::string join(const std::vector<std::string>& v) {
    std::string s;
    for (std::size_t i = 0; i < v.size(); ++i) s += (i ? "\n" : "") + v[i];
    return s;
}

std::string stats9(const hdf::ModelStats& s) {
    return std::to_string(s.arc) + " " + std::to_string(s.models) + " " + std::to_string(s.mat) + " " +
           std::to_string(s.shp) + " " + std::to_string(s.jnt) + " " + std::to_string(s.tex) + " " +
           std::to_string(s.anm) + " " + std::to_string(s.files) + " " + std::to_string(s.dl);
}

// the fixed (convert_j3d + mat4fix) models by name, as the generator's fixed_models
std::map<std::string, Bytes> fixed_models() {
    std::map<std::string, Bytes> out;
    for (const auto& v : kModelVecs) {
        const Bytes m = unhex(v.model);
        std::optional<View> gtx;
        Bytes g;
        if (v.gtx) {
            g = unhex(v.gtx);
            gtx = View(g);
        }
        auto c = j3d::convert_j3d(m, gtx);
        if (!c) continue;
        auto f = j3d::mat4fix(*c);
        if (f) out[v.name] = f->data;
    }
    return out;
}

// make_tmpk of the generator: 'TMPK', count, 0x20, 0; entries; names; data 32-aligned
Bytes make_tmpk(const std::vector<std::pair<std::string, Bytes>>& entries) {
    const std::size_t n = entries.size();
    Bytes names;
    std::vector<u32> noffs;
    for (const auto& [name, data] : entries) {
        noffs.push_back(static_cast<u32>(0x10 + 16 * n + names.size()));
        names.insert(names.end(), name.begin(), name.end());
        names.push_back(0);
    }
    Bytes out(0x10 + 16 * n, 0);
    std::memcpy(out.data(), "TMPK", 4);
    io::put32(out, 4, static_cast<u32>(n));
    io::put32(out, 8, 0x20);
    out.insert(out.end(), names.begin(), names.end());
    for (std::size_t i = 0; i < n; ++i) {
        while (out.size() % 32) out.push_back(0);
        io::put32(out, 0x10 + 16 * i, noffs[i]);
        io::put32(out, 0x10 + 16 * i + 4, static_cast<u32>(out.size()));
        io::put32(out, 0x10 + 16 * i + 8, static_cast<u32>(entries[i].second.size()));
        out.insert(out.end(), entries[i].second.begin(), entries[i].second.end());
    }
    return out;
}

Bytes zeros_after(std::string_view head, std::size_t n) {
    Bytes b(head.begin(), head.end());
    b.insert(b.end(), n, u8{0});
    return b;
}

