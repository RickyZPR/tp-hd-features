using detail::bad;
using io::Json;
using io::JsonArray;
using io::JsonObject;

constexpr const char* kOutDir = "res/cave/amiibo/";
// The 6 PNGs a reader uses (plan 4 drop list: the other 19 amiibo PNGs are dropped).
constexpr const char* kKept[] = {"popup.png", "tt_input_glow.png", "tt_input_prompt.png", "amiibo_wolflink.png",
                                 "font_amiibo.png", "los_heart.png"};
// hdtext.SCHEMA_VERSION and the two fixed notes of layout.json
constexpr int kSchemaVersion = 1;
constexpr const char* kNote =
    "Generated by tools/pipeline/hdtext.py from the TP HD dump (zelda_amiibo_progress.blo, "
    "zelda_file_select_los_record.blo); local use only. Coordinates: J2D 608x448 base screen.";
constexpr const char* kAnimNote =
    "amiibo.arc has no J2D animation files: HD code drives the scan screen "
    "(dFile_amiibo_c / AmiiboInterfaceThread; INFERRED)";

bool kept(const std::string& out_name) {
    return std::any_of(std::begin(kKept), std::end(kKept), [&](const char* k) { return out_name == k; });
}

// One textures[name] value, in insertion order (a repeated name keeps its first position, takes the new value).
struct TexRow {
    std::string name;
    std::string file;
    u32 w = 0, h = 0;
    std::string source;
};

struct State {
    const Options& opt;
    std::stop_token stop;
    UiOut out;
    std::vector<TexRow> textures;
    std::vector<std::string> missing;  // res['missing'] (log only)

    bool has(const std::string& name) const {
        return std::any_of(textures.begin(), textures.end(), [&](const TexRow& t) { return t.name == name; });
    }

    // export(tm, name, out_name, source)
    Result<void> export_(const io::Tmpk* tm, const std::string& name, const std::string& out_name,
                         const char* source) {
        if (stop.stop_requested()) return detail::stop_error();
        std::optional<View> g;
        if (tm != nullptr) g = detail::tmpk_find(*tm, name + ".bti.gtx");
        if (!g) {
            missing.push_back(std::string(source) + ":" + name);
            return {};
        }
        u32 w = 0, h = 0;
        const bool keep = kept(out_name);
        if (keep || opt.dropped) {
            auto r = detail::gtx_rgba(*g);  // _gtx_rgba(g)
            if (!r) return std::unexpected(r.error());
            w = r->w;
            h = r->h;
            (keep ? out.pngs : out.dropped).push_back(Png{kOutDir + out_name, w, h, std::move(r->rgba)});
        } else {
            auto s = tex::gtx_surfaces(*g);  // w, h of _gtx_rgba without the pixels
            if (!s) return std::unexpected(s.error());
            if (s->empty()) return bad("GTX has no surface");
            auto li = tex::level_info((*s)[0], 0);
            if (!li) return std::unexpected(li.error());
            w = li->width;
            h = li->height;
        }
        TexRow row{name, out_name, w, h, source};
        auto it = std::find_if(textures.begin(), textures.end(), [&](const TexRow& t) { return t.name == name; });
        if (it != textures.end())
            *it = std::move(row);
        else
            textures.push_back(std::move(row));
        return {};
    }
};

// tmpk(d, n): hdpack.Tmpk(hdpack.read_any(p)). Every pack is one of the 136 checked inputs, so a missing one
// is an error here (Python would skip its textures and write a different layout.json).
Result<io::Tmpk> tmpk(const Source& hd, const std::string& rel, std::stop_token stop) {
    auto raw = hd.read(rel, stop);
    if (!raw) return std::unexpected(raw.error());
    return io::tmpk_from_gz(*raw, stop);
}

Result<io::Rarc> rarc(const Source& hd, const std::string& rel, std::stop_token stop) {
    auto raw = hd.read(rel, stop);
    if (!raw) return std::unexpected(raw.error());
    return io::rarc_read(*raw);
}

Json str_list(const std::vector<std::string>& v) {
    JsonArray a;
    for (const auto& s : v) a.emplace_back(s);
    return a;
}

