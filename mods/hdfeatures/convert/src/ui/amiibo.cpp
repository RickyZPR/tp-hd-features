Result<UiOut> build_amiibo(const Source& hd, std::stop_token stop) { return build_amiibo(hd, stop, Options{}); }

Result<UiOut> build_amiibo(const Source& hd, std::stop_token stop, const Options& opt) {
    if (detail::stopped(stop)) return detail::stop_error();
    State st{opt, stop, {}, {}, {}};
    JsonObject screens;
    std::vector<std::string> animations;
    {
        // arc_p = LayoutRevo/amiibo.arc, tm = LayoutRevo/amiibo.pack.gz
        auto a = rarc(hd, "res/LayoutRevo/amiibo.arc", stop);
        if (!a) return std::unexpected(a.error());
        auto tm = tmpk(hd, "res/LayoutRevo/amiibo.pack.gz", stop);
        if (!tm) return std::unexpected(tm.error());
        const io::RarcMember* blo = a->get("zelda_amiibo_progress.blo");
        if (blo == nullptr) return bad("amiibo.arc: no zelda_amiibo_progress.blo");  // None.data()
        auto bd = a->data(*blo);
        if (!bd) return std::unexpected(bd.error());
        auto scr = detail::parse_blo(*bd);
        if (!scr) return std::unexpected(scr.error());
        screens.emplace_back("zelda_amiibo_progress", std::move(scr->json));
        // names = sorted({m.name[:-4] for m in a.files() if m.name.lower().endswith('.bti')})
        std::set<std::string> names;
        for (const io::RarcMember& m : a->members) {
            const std::string low = detail::ascii_lower(m.name);
            if (detail::ends_with(low, ".bti")) names.insert(m.name.substr(0, m.name.size() - 4));
            // m.name.lower().split('.')[-1] in (animation extensions)
            const auto dot = low.rfind('.');
            const std::string ext = dot == std::string::npos ? low : low.substr(dot + 1);
            for (const char* e : {"bck", "bpk", "btk", "brk", "btp", "bca", "bla", "bva"})
                if (ext == e) animations.push_back(m.path);
        }
        std::sort(animations.begin(), animations.end());
        for (const std::string& n : names)
            if (auto r = st.export_(&*tm, n, n + ".png", "LayoutRevo/amiibo.pack.gz"); !r)
                return std::unexpected(r.error());
    }
    {
        // sv = Layout/saveres.arc, stm = Layout/saveres.pack.gz
        auto stm = tmpk(hd, "res/Layout/saveres.pack.gz", stop);
        if (!stm) return std::unexpected(stm.error());
        if (auto r = st.export_(&*stm, "amiibo_wolflink", "amiibo_wolflink.png", "Layout/saveres.pack.gz"); !r)
            return std::unexpected(r.error());
        auto sa = rarc(hd, "res/Layout/saveres.arc", stop);
        if (!sa) return std::unexpected(sa.error());
        if (const io::RarcMember* m = sa->get("zelda_file_select_los_record.blo")) {
            auto bd = sa->data(*m);
            if (!bd) return std::unexpected(bd.error());
            auto scr = detail::parse_blo(*bd);
            if (!scr) return std::unexpected(scr.error());
            const std::vector<std::string> used = scr->textures_used;
            screens.emplace_back("zelda_file_select_los_record", std::move(scr->json));
            for (const std::string& n : used)
                if (!st.has(n))
                    if (auto r = st.export_(&*stm, n, "los_" + n + ".png", "Layout/saveres.pack.gz"); !r)
                        return std::unexpected(r.error());
        }
    }
    {
        auto mtm = tmpk(hd, "res/LayoutRevo/main2DR.pack.gz", stop);
        if (!mtm) return std::unexpected(mtm.error());
        for (const char* n : {"font_amiibo", "font_nfc"})
            if (auto r = st.export_(&*mtm, n, std::string(n) + ".png", "LayoutRevo/main2DR.pack.gz"); !r)
                return std::unexpected(r.error());
    }
    {
        auto itm = tmpk(hd, "res/Layout/itemicon.pack.gz", stop);
        if (!itm) return std::unexpected(itm.error());
        if (auto r = st.export_(&*itm, "st_figure", "st_figure.png", "Layout/itemicon.pack.gz"); !r)
            return std::unexpected(r.error());
    }
    JsonObject textures;
    for (const TexRow& t : st.textures)
        textures.emplace_back(t.name, JsonObject{{"file", t.file}, {"w", t.w}, {"h", t.h}, {"source", t.source}});
    JsonObject layout;
    layout.emplace_back("version", kSchemaVersion);
    layout.emplace_back("note", kNote);
    layout.emplace_back("animations", str_list(animations));
    layout.emplace_back("animation_note", kAnimNote);
    layout.emplace_back("textures", std::move(textures));
    layout.emplace_back("screens", std::move(screens));
    io::JsonStyle style;
    style.indent = 1;
    style.item_sep = ",";
    std::string text = io::json_dumps(Json(std::move(layout)), style);
    text += '\n';
    st.out.files.emplace_back(std::string(kOutDir) + "layout.json", Bytes(text.begin(), text.end()));
    return std::move(st.out);
}

