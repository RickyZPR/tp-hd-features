// Module U: the amiibo / Cave of Shadows record art and layout (pipeline/hdtext.py build_amiibo).
//
// res/cave/amiibo/layout.json  json.dumps(layout, indent=1) + '\n' (io::json_dumps, ensure_ascii): the textures
//     dict (all 25 exported textures, kept or not) and the parse_blo dicts of zelda_amiibo_progress.blo (HD
//     LayoutRevo/amiibo.arc) and zelda_file_select_los_record.blo (HD Layout/saveres.arc).
// res/cave/amiibo/<6 kept PNGs>  popup, tt_input_glow, tt_input_prompt, amiibo_wolflink, font_amiibo, los_heart.
// The other 19 PNGs are on the drop list: by default only their size is read (level_info of surface 0, which is
// what _gtx_rgba returns as w, h); Options::dropped decodes them too.
#include "hdf/io.hpp"
#include "hdf/tex.hpp"
#include "hdf/ui.hpp"
#include "ui/ui_internal.hpp"

#include <algorithm>
